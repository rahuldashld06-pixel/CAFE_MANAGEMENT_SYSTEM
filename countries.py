def city_of(zone):
    """
    The part of a zone name people would recognise.

    "America/Argentina/Buenos_Aires" -> "Buenos Aires". Only ever shown
    beside a country that keeps more than one clock, where the country's
    name alone would not say which.
    """
    return zone.rsplit("/", 1)[-1].replace("_", " ")
