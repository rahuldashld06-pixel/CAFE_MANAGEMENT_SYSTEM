"""
Countries, and the clocks they keep.

The time zone setting used to be the raw IANA list - two thousand-odd
entries reading "Indian/Chagos", "America/Argentina/Catamarca",
"Etc/GMT+7". Those names are addresses in a database, not answers to the
question the page is actually asking, which is "where is this cafe?".
Somebody running a cafe in Delhi should find India, not have to know
that India's clock is filed under Kolkata.

So the picker asks for a country. Most countries keep one clock and are
one line. The two dozen that keep several list them, because there is no
honest way to collapse them: Brazil really is four hours wide, and an
"Australia" that quietly meant Sydney would tell Perth the wrong time
twice a day.

Nothing here is authority. IANA is, and every zone below is checked
against the ones this machine actually has before it reaches a page - a
name that is wrong or has been retired drops out rather than being
offered. See timezone_choices() in app.py.

The zone is what gets stored; the country is only how it was chosen. So
correcting a country's name here can never move a cafe's clock.
"""

